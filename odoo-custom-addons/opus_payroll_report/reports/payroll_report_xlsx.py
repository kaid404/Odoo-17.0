        sheet.write(row, col + 20, 'Overtimes', text_wrap)
        sheet.write(row, col + 21, 'Loan', text_wrap)
        sheet.write(row, col + 22, 'Increment', text_wrap)
        sheet.write(row, col + 23, 'Reimbursement', text_wrap)
        sheet.write(row, col + 24, 'Arrears', text_wrap)
        sheet.write(row, col + 25, 'PF Employee', text_wrap)
        sheet.write(row, col + 26, 'EOBI Employee', text_wrap)
